#include <stdio.h>

int main() {
    int r[] = {17, 42, 42, 7, 24, 24, 17, 54, 17}; 
    int i, n, e, c = 0, f = 0;

    // حساب طول المصفوفة
    n = sizeof(r) / sizeof(r[0]); 

    // نبدأ بأول عنصر في المصفوفة
    e = r[0]; 

    for (i = 1; i < n; i++) {
        // إذا وجدنا رقم يشبه الذي قبله ولم نكن قد سجلناه كـ "تجمع" بعد
        if (r[i] == e && f == 0) {
            c++;      // زد العداد
            f = 1;    // ارفع العلم لكي لا نحسب نفس المجموعة مرة أخرى
        } 
        
        // إذا تغير الرقم، نقوم بتصفير العلم وتغيير الرقم الذي نراقبه
        if (r[i] != e) {
            f = 0;    
            e = r[i]; 
        }
    }

    printf("Number of clumps: %d", c);

    return 0;
}